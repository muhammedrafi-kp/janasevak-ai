import { Schema, model, Document } from "mongoose";

export enum UserRole {
  CITIZEN = "citizen",
  AUTHORITY = "authority",
}

export interface IUser extends Document {
  name: string;
  email: string;
  password: string;
  role: UserRole;
  createdAt: Date;
  updatedAt: Date;
}

const userSchema = new Schema<IUser>(
  {
    name: {
      type: String,
      required: true,
      trim: true,
    },

    email: {
      type: String,
      required: true,
      unique: true,
      lowercase: true,
    },

    password: {
      type: String,
      required: true,
    },

    role: {
      type: String,
      enum: Object.values(UserRole),
      default: UserRole.CITIZEN,
    },
  },
  {
    timestamps: true,
  }
);

export default model<IUser>("User", userSchema);